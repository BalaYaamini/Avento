const supabase = require('../config/supabaseClient');

const checkIsEventOrganizer = async (event, user) => {
  if (!user || !user.id) return false;
  if (user.roles && user.roles.includes('admin')) return true;
  if (String(event.organizer_id) === String(user.id) ||
      String(event.student_organizer_id) === String(user.id) ||
      String(event.proposed_by) === String(user.id) ||
      String(event.created_by) === String(user.id) ||
      String(event.faculty_id) === String(user.id)) {
    return true;
  }

  const { data: org } = await supabase
    .from('event_organizers')
    .select('id')
    .eq('event_id', event.id)
    .eq('student_id', user.id)
    .maybeSingle();

  if (org) return true;

  const { data: member } = await supabase
    .from('event_members')
    .select('id')
    .eq('event_id', event.id)
    .eq('user_id', user.id)
    .maybeSingle();

  return !!member;
};

// Helper to auto-generate default periodic attendance intervals (default 4h)
const autoGenerateDefaultPeriods = async (event, intervalHours = 4, customStart = null, customEnd = null) => {
  try {
    const startDate = customStart ? new Date(customStart) : (event.date ? new Date(event.date) : new Date());
    let endDate = customEnd ? new Date(customEnd) : (event.end_date ? new Date(event.end_date) : new Date(startDate.getTime() + 12 * 60 * 60 * 1000));
    if (endDate <= startDate) {
      endDate = new Date(startDate.getTime() + 12 * 60 * 60 * 1000);
    }

    const totalDurationMs = endDate.getTime() - startDate.getTime();
    const intervalMs = (Number(intervalHours) || 4) * 60 * 60 * 1000;
    const periodCount = Math.max(1, Math.ceil(totalDurationMs / intervalMs));

    const newPeriods = [];
    for (let i = 0; i < periodCount; i++) {
      const pStart = new Date(startDate.getTime() + i * intervalMs);
      const pEnd = new Date(Math.min(endDate.getTime(), pStart.getTime() + intervalMs));
      newPeriods.push({
        event_id: event.id,
        period_name: `Period ${i + 1} (${pStart.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })} - ${pEnd.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })})`,
        start_time: pStart.toISOString(),
        end_time: pEnd.toISOString()
      });
    }

    const { data: inserted, error } = await supabase
      .from('event_attendance_periods')
      .insert(newPeriods)
      .select();

    if (error) {
      console.error('Error inserting default periods:', error);
      return [];
    }
    return inserted || [];
  } catch (err) {
    console.error('Error auto-generating default periods:', err);
    return [];
  }
};

// Verify QR token and mark attendance (supports configurable periodic attendance)
exports.verifyQrToken = async (req, res) => {
  try {
    let { registrationId, eventId } = req.body;
    if (!registrationId) return res.status(400).json({ message: 'Registration ID is required.' });
    if (!eventId) return res.status(400).json({ message: 'Event ID is required.' });

    // Handle JSON payload string if scanner outputs JSON
    if (typeof registrationId === 'string' && registrationId.trim().startsWith('{')) {
      try {
        const parsed = JSON.parse(registrationId);
        if (parsed.registrationId) registrationId = parsed.registrationId;
        else if (parsed.id) registrationId = parsed.id;
      } catch (e) {}
    }

    const cleanToken = String(registrationId).trim();
    const isUUID = /^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$/.test(cleanToken);

    let registration = null;

    if (isUUID) {
      // Lookup 1: Query by registration ID UUID
      const { data: regById } = await supabase
        .from('event_registrations')
        .select('*, eventId:events(*)')
        .eq('id', cleanToken)
        .maybeSingle();

      if (regById) {
        registration = regById;
      } else {
        // Lookup 2: Query by user_id for this event
        const { data: regByUser } = await supabase
          .from('event_registrations')
          .select('*, eventId:events(*)')
          .eq('event_id', eventId)
          .eq('user_id', cleanToken)
          .maybeSingle();
        if (regByUser) registration = regByUser;
      }
    } else {
      // Lookup 3: Non-UUID token (e.g. roll number, email, or synthetic token)
      if (cleanToken.includes('_')) {
        const parts = cleanToken.split('_');
        const candidateUserId = parts[parts.length - 1];
        if (/^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$/.test(candidateUserId)) {
          const { data: regBySynthetic } = await supabase
            .from('event_registrations')
            .select('*, eventId:events(*)')
            .eq('event_id', eventId)
            .eq('user_id', candidateUserId)
            .maybeSingle();
          if (regBySynthetic) registration = regBySynthetic;
        }
      }

      if (!registration) {
        // Search profile by roll_number or email
        const { data: matchedProfile } = await supabase
          .from('profiles')
          .select('id')
          .or(`roll_number.ilike.${cleanToken},email.ilike.${cleanToken}`)
          .maybeSingle();

        if (matchedProfile && matchedProfile.id) {
          const { data: regByProfile } = await supabase
            .from('event_registrations')
            .select('*, eventId:events(*)')
            .eq('event_id', eventId)
            .eq('user_id', matchedProfile.id)
            .maybeSingle();
          if (regByProfile) registration = regByProfile;
        }
      }
    }

    if (!registration) {
      return res.status(404).json({ message: 'Invalid Registration ID or Participant Not Registered for this Event.' });
    }

    // Phase 2 Validation: Check if QR belongs to the currently selected event
    if (String(registration.event_id) !== String(eventId)) {
      return res.status(400).json({ message: 'This QR code belongs to a different event.' });
    }

    // Verify event details
    const { data: event } = await supabase
      .from('events')
      .select('*')
      .eq('id', registration.event_id)
      .maybeSingle();

    if (!event) return res.status(404).json({ message: 'Event not found.' });

    const isOwner = await checkIsEventOrganizer(event, req.user);
    if (!isOwner) return res.status(403).json({ message: 'Access denied. Organizer permissions required to mark attendance.' });

    // Fetch student profile info
    const { data: studentProfile } = await supabase
      .from('profiles')
      .select('name, roll_number')
      .eq('id', registration.user_id)
      .maybeSingle();

    const studentInfo = {
      name: studentProfile?.name || 'Participant',
      rollNumber: studentProfile?.roll_number || 'N/A',
      event: event.title,
      attendance_status: 'Present'
    };

    // ── PERIODIC ATTENDANCE LOGIC ───────────────────────────────────────
    const now = new Date();

    // Fetch existing periods for this event
    let { data: periods } = await supabase
      .from('event_attendance_periods')
      .select('*')
      .eq('event_id', event.id)
      .order('start_time', { ascending: true });

    // If no periods exist and periodic attendance is enabled, auto-generate default 4h periods
    if ((!periods || periods.length === 0) && event.periodic_attendance_enabled !== false) {
      periods = await autoGenerateDefaultPeriods(event, event.period_interval_hours || 4);
    }

    // Check if attendance is closed based on configured periods bounds
    if (periods && periods.length > 0) {
      const lastPeriod = periods[periods.length - 1];
      if (new Date(lastPeriod.end_time) < now) {
        return res.status(403).json({ success: false, message: 'Attendance is closed because all configured attendance periods for this event have concluded.' });
      }
    } else if (event.end_date && new Date(event.end_date) < now) {
      return res.status(403).json({ success: false, message: 'Attendance is closed because this event has already ended.' });
    }

    // If periods exist, find active period using server time (now)
    let activePeriod = null;
    let nextUpcomingPeriod = null;

    if (periods && periods.length > 0) {
      activePeriod = periods.find(p => new Date(p.start_time) <= now && now <= new Date(p.end_time));
      if (!activePeriod) {
        nextUpcomingPeriod = periods.find(p => new Date(p.start_time) > now);
      }
    }

    // CASE 1: Periodic Attendance Active Period Found
    if (activePeriod) {
      // Check if attendance is already recorded for THIS registration and THIS active period
      const { data: existingRecord } = await supabase
        .from('event_periodic_attendance')
        .select('*')
        .eq('registration_id', registration.id)
        .eq('attendance_period_id', activePeriod.id)
        .maybeSingle();

      // Check if food coupon option is enabled for active period or auto-detected in period name
      const hasFoodCoupon = activePeriod.includes_food_coupon === true ||
        (activePeriod.period_name && /food|meal|coupon|lunch|dinner|breakfast|snack/i.test(activePeriod.period_name));
      const foodCouponLabel = activePeriod.food_coupon_name || 'Food / Meal Coupon';

      if (existingRecord) {
        const scanTimeStr = new Date(existingRecord.scanned_at).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' });
        return res.status(200).json({
          success: true,
          alreadyMarked: true,
          message: `Attendance already marked for this period (${activePeriod.period_name})${hasFoodCoupon ? ' (Food coupon already redeemed)' : ''} at ${scanTimeStr}.`,
          periodName: activePeriod.period_name,
          includesFoodCoupon: hasFoodCoupon,
          foodCouponName: foodCouponLabel,
          originalScanTime: existingRecord.scanned_at,
          student: studentInfo
        });
      }

      // Mark attendance for active period
      const { error: insertErr } = await supabase
        .from('event_periodic_attendance')
        .insert({
          event_id: event.id,
          registration_id: registration.id,
          attendance_period_id: activePeriod.id,
          scanned_at: now.toISOString(),
          scanned_by: req.user.id
        });

      if (insertErr && insertErr.code === '23505') {
        // Unique constraint fallback check
        return res.status(200).json({
          success: true,
          alreadyMarked: true,
          message: `Attendance already marked for this period (${activePeriod.period_name})${hasFoodCoupon ? ' (Food coupon already redeemed)' : ''}.`,
          periodName: activePeriod.period_name,
          includesFoodCoupon: hasFoodCoupon,
          foodCouponName: foodCouponLabel,
          student: studentInfo
        });
      } else if (insertErr) {
        console.error('Error inserting periodic attendance:', insertErr);
      }

      // Also ensure main registration status is 'Present'
      await supabase
        .from('event_registrations')
        .update({ attendance_status: 'Present' })
        .eq('id', registration.id);

      // Fetch progress (count of marked periods for this participant)
      const { count: markedCount } = await supabase
        .from('event_periodic_attendance')
        .select('*', { count: 'exact', head: true })
        .eq('registration_id', registration.id);

      const totalPeriodsCount = periods.length;
      const progressStr = `${markedCount || 1}/${totalPeriodsCount}`;
      const foodMsg = hasFoodCoupon ? ` Food Coupon (${foodCouponLabel}) Redeemed Together!` : '';

      return res.json({
        success: true,
        alreadyMarked: false,
        message: `Attendance marked for ${activePeriod.period_name}!${foodMsg} (${progressStr})`,
        periodName: activePeriod.period_name,
        includesFoodCoupon: hasFoodCoupon,
        foodCouponName: foodCouponLabel,
        scannedAt: now.toISOString(),
        progress: progressStr,
        student: studentInfo
      });
    }

    // CASE 2: No Active Period Right Now (Upcoming or Past Periods)
    if (periods && periods.length > 0 && !activePeriod) {
      if (nextUpcomingPeriod) {
        const startTimeStr = new Date(nextUpcomingPeriod.start_time).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
        return res.status(400).json({
          message: `No active attendance period right now. Next period (${nextUpcomingPeriod.period_name}) starts at ${startTimeStr}.`
        });
      }
      return res.status(400).json({
        message: 'All attendance periods for this event have concluded.'
      });
    }

    // CASE 3: Standard Non-Periodic Attendance Fallback
    if (registration.attendance_status === 'Present') {
      return res.status(200).json({
        success: true,
        alreadyMarked: true,
        message: 'Attendance already marked as Present for this participant.',
        student: studentInfo
      });
    }

    await supabase
      .from('event_registrations')
      .update({ attendance_status: 'Present' })
      .eq('id', registration.id);

    return res.json({
      success: true,
      alreadyMarked: false,
      message: 'Attendance marked successfully',
      student: studentInfo
    });
  } catch (err) {
    console.error('Attendance Scanner Exception:', err);
    return res.status(500).json({ message: 'Server error scanning QR code.', error: err.message });
  }
};

// Get periodic attendance dashboard data for an event (organizer view)
exports.getEventPeriodicAttendance = async (req, res) => {
  try {
    const { eventId } = req.params;
    const { data: event } = await supabase.from('events').select('*').eq('id', eventId).single();
    if (!event) return res.status(404).json({ message: 'Event not found.' });

    const isOwner = await checkIsEventOrganizer(event, req.user);
    if (!isOwner) return res.status(403).json({ message: 'Access denied.' });

    const now = new Date();

    // Fetch periods
    let { data: periods } = await supabase
      .from('event_attendance_periods')
      .select('*')
      .eq('event_id', eventId)
      .order('start_time', { ascending: true });

    if ((!periods || periods.length === 0) && event.periodic_attendance_enabled !== false) {
      periods = await autoGenerateDefaultPeriods(event, event.period_interval_hours || 4);
    }

    periods = periods || [];

    // Active period & Next period based on server time
    const activePeriod = periods.find(p => new Date(p.start_time) <= now && now <= new Date(p.end_time)) || null;
    const nextPeriod = periods.find(p => new Date(p.start_time) > now) || null;

    let timeRemainingSeconds = 0;
    if (activePeriod) {
      timeRemainingSeconds = Math.max(0, Math.floor((new Date(activePeriod.end_time).getTime() - now.getTime()) / 1000));
    }

    // Fetch total registrations
    const { data: registrations } = await supabase
      .from('event_registrations')
      .select('id, user_id, status, attendance_status, profiles:user_id(id, name, email, roll_number)')
      .eq('event_id', eventId)
      .in('status', ['registered', 'accepted', 'pending']);

    const totalRegistered = (registrations || []).length;

    // Fetch all periodic attendance records for this event with participant profiles
    const { data: periodicRecords } = await supabase
      .from('event_periodic_attendance')
      .select('*, attendance_period_id, registration_id, scanned_at, registration:event_registrations(id, user_id, profiles:user_id(name, email, roll_number))')
      .eq('event_id', eventId)
      .order('scanned_at', { ascending: false });

    const records = periodicRecords || [];

    // Create detailed scan logs array for hour-to-hour timestamp view
    const scanLogs = records.map(r => {
      const periodObj = periods.find(p => p.id === r.attendance_period_id);
      const profile = r.registration?.profiles || {};
      const hasFood = !!(periodObj?.includes_food_coupon || (periodObj?.period_name && /food|meal|coupon|lunch|dinner|breakfast|snack/i.test(periodObj.period_name)));
      return {
        id: r.id,
        scannedAt: r.scanned_at,
        registrationId: r.registration_id,
        periodId: r.attendance_period_id,
        periodName: periodObj ? periodObj.period_name : 'Checkpoint',
        includesFoodCoupon: hasFood,
        foodCouponName: periodObj?.food_coupon_name || 'Food / Meal Coupon',
        participantName: profile.name || 'Participant',
        rollNumber: profile.roll_number || 'N/A',
        email: profile.email || 'N/A'
      };
    });

    // Attach marked count per period
    const periodsWithMetrics = periods.map(p => {
      const markedForPeriod = records.filter(r => r.attendance_period_id === p.id);
      return {
        ...p,
        markedCount: markedForPeriod.length,
        unmarkedCount: Math.max(0, totalRegistered - markedForPeriod.length),
        isActive: activePeriod ? activePeriod.id === p.id : false
      };
    });

    let activePeriodMarkedCount = 0;
    if (activePeriod) {
      activePeriodMarkedCount = records.filter(r => r.attendance_period_id === activePeriod.id).length;
    }
    const activePeriodUnmarkedCount = Math.max(0, totalRegistered - activePeriodMarkedCount);

    // Calculate progress for each participant
    const minCheckpoints = event.min_certificate_checkpoints || null;
    const minPercentage = Number(event.min_certificate_percentage) || 75;
    const totalPeriodsCount = periods.length || 1;

    const participantProgress = (registrations || []).map(reg => {
      const regRecords = records.filter(r => r.registration_id === reg.id);
      const markedCount = regRecords.length;
      const percentage = Math.round((markedCount / totalPeriodsCount) * 100);
      
      let isEligible = false;
      if (minCheckpoints !== null && minCheckpoints > 0) {
        isEligible = markedCount >= minCheckpoints;
      } else {
        isEligible = percentage >= minPercentage;
      }

      return {
        registrationId: reg.id,
        userId: reg.user_id,
        name: reg.profiles?.name || 'Participant',
        rollNumber: reg.profiles?.roll_number || 'N/A',
        email: reg.profiles?.email || 'N/A',
        markedCount,
        totalPeriods: totalPeriodsCount,
        progressStr: `${markedCount}/${totalPeriodsCount}`,
        percentage,
        isEligible,
        records: regRecords
      };
    });

    // Compute effective end date if event.end_date is null
    const lastPeriodEndTime = (periods && periods.length > 0) ? periods[periods.length - 1].end_time : null;
    const effectiveEndDate = event.end_date || lastPeriodEndTime;

    return res.json({
      success: true,
      event: {
        id: event.id,
        title: event.title,
        date: event.date,
        end_date: effectiveEndDate,
        periodic_attendance_enabled: event.periodic_attendance_enabled,
        period_interval_hours: event.period_interval_hours || 4,
        min_certificate_checkpoints: minCheckpoints,
        min_certificate_percentage: minPercentage
      },
      serverTime: now.toISOString(),
      periods: periodsWithMetrics,
      activePeriod,
      nextPeriod,
      timeRemainingSeconds,
      totalRegistered,
      activePeriodMarkedCount,
      activePeriodUnmarkedCount,
      participantProgress,
      scanLogs
    });
  } catch (err) {
    console.error('Error in getEventPeriodicAttendance:', err);
    return res.status(500).json({ message: 'Server error fetching periodic attendance data.', error: err.message });
  }
};

// Auto-generate periods based on interval and customizable event start/end times
exports.autoGeneratePeriods = async (req, res) => {
  try {
    const { eventId } = req.params;
    const { intervalHours, eventStart, eventEnd } = req.body;
    const hours = Number(intervalHours) || 4;

    const { data: event } = await supabase.from('events').select('*').eq('id', eventId).single();
    if (!event) return res.status(404).json({ message: 'Event not found.' });

    const isOwner = await checkIsEventOrganizer(event, req.user);
    if (!isOwner) return res.status(403).json({ message: 'Access denied.' });

    // Build update payload for customizable event start/end times
    const updatePayload = { period_interval_hours: hours, periodic_attendance_enabled: true };
    if (eventStart) updatePayload.date = new Date(eventStart).toISOString();
    if (eventEnd) updatePayload.end_date = new Date(eventEnd).toISOString();

    let updatedEvent = null;
    const { data: uEv, error: uErr } = await supabase
      .from('events')
      .update(updatePayload)
      .eq('id', eventId)
      .select()
      .single();

    if (uErr) {
      delete updatePayload.end_date;
      const { data: uEv2 } = await supabase.from('events').update(updatePayload).eq('id', eventId).select().single();
      updatedEvent = uEv2;
    } else {
      updatedEvent = uEv;
    }

    const targetEvent = updatedEvent || event;

    // Delete existing periods
    await supabase.from('event_attendance_periods').delete().eq('event_id', eventId);

    const periods = await autoGenerateDefaultPeriods(targetEvent, hours, eventStart, eventEnd);

    const effectiveEnd = eventEnd ? new Date(eventEnd).toISOString() : (targetEvent.end_date || (periods.length > 0 ? periods[periods.length - 1].end_time : null));

    return res.json({ 
      success: true, 
      message: `Auto-generated ${periods.length} periodic attendance checkpoints (${hours}-hour intervals).`, 
      periods,
      event: {
        ...targetEvent,
        date: eventStart ? new Date(eventStart).toISOString() : targetEvent.date,
        end_date: effectiveEnd
      } 
    });
  } catch (err) {
    console.error('Error auto-generating periods:', err);
    return res.status(500).json({ message: 'Server error generating periods.', error: err.message });
  }
};

// Create a custom attendance period
exports.createCustomPeriod = async (req, res) => {
  try {
    const { eventId } = req.params;
    const { periodName, startTime, endTime, includesFoodCoupon, includes_food_coupon, foodCouponName, food_coupon_name } = req.body;

    if (!periodName || !startTime || !endTime) {
      return res.status(400).json({ message: 'Period name, start time, and end time are required.' });
    }

    const { data: event } = await supabase.from('events').select('*').eq('id', eventId).single();
    if (!event) return res.status(404).json({ message: 'Event not found.' });

    const isOwner = await checkIsEventOrganizer(event, req.user);
    if (!isOwner) return res.status(403).json({ message: 'Access denied.' });

    const hasFood = !!(includesFoodCoupon || includes_food_coupon);
    const couponName = (foodCouponName || food_coupon_name || 'Food / Meal Coupon').trim();

    let cleanName = periodName.replace(/(?:🍔\s*)?\[Food Coupon Included\]/gi, '').trim();
    if (hasFood) {
      cleanName = `${cleanName} [Food Coupon Included]`;
    }

    let insertPayload = {
      event_id: eventId,
      period_name: cleanName,
      start_time: new Date(startTime).toISOString(),
      end_time: new Date(endTime).toISOString(),
      includes_food_coupon: hasFood,
      food_coupon_name: couponName
    };

    let newPeriod = null;
    const { data: inserted, error } = await supabase
      .from('event_attendance_periods')
      .insert(insertPayload)
      .select()
      .single();

    if (error && (error.message?.includes('includes_food_coupon') || error.code === 'PGRST204')) {
      delete insertPayload.includes_food_coupon;
      delete insertPayload.food_coupon_name;
      const { data: fbPeriod, error: fbErr } = await supabase
        .from('event_attendance_periods')
        .insert(insertPayload)
        .select()
        .single();
      if (fbErr) throw fbErr;
      newPeriod = { ...fbPeriod, includes_food_coupon: hasFood, food_coupon_name: couponName };
    } else if (error) {
      throw error;
    } else {
      newPeriod = inserted;
    }

    return res.json({ success: true, message: 'Custom attendance period created successfully.', period: newPeriod });
  } catch (err) {
    console.error('Error creating custom period:', err);
    return res.status(500).json({ message: 'Server error creating period.', error: err.message });
  }
};

// Update an attendance period
exports.updatePeriod = async (req, res) => {
  try {
    const { eventId, periodId } = req.params;
    const { periodName, startTime, endTime, includesFoodCoupon, includes_food_coupon, foodCouponName, food_coupon_name } = req.body;

    const { data: event } = await supabase.from('events').select('*').eq('id', eventId).single();
    if (!event) return res.status(404).json({ message: 'Event not found.' });

    const isOwner = await checkIsEventOrganizer(event, req.user);
    if (!isOwner) return res.status(403).json({ message: 'Access denied.' });

    const hasFood = includesFoodCoupon !== undefined ? !!includesFoodCoupon : (includes_food_coupon !== undefined ? !!includes_food_coupon : undefined);
    const couponName = foodCouponName !== undefined ? foodCouponName.trim() : (food_coupon_name !== undefined ? food_coupon_name.trim() : undefined);

    let cleanName = periodName ? periodName.replace(/(?:🍔\s*)?\[Food Coupon Included\]/gi, '').trim() : undefined;
    if (hasFood && cleanName) {
      cleanName = `${cleanName} [Food Coupon Included]`;
    }

    let updatePayload = {
      period_name: cleanName,
      start_time: startTime ? new Date(startTime).toISOString() : undefined,
      end_time: endTime ? new Date(endTime).toISOString() : undefined,
      includes_food_coupon: hasFood,
      food_coupon_name: couponName
    };

    let updatedPeriod = null;
    const { data: uPeriod, error } = await supabase
      .from('event_attendance_periods')
      .update(updatePayload)
      .eq('id', periodId)
      .eq('event_id', eventId)
      .select()
      .single();

    if (error && (error.message?.includes('includes_food_coupon') || error.code === 'PGRST204')) {
      delete updatePayload.includes_food_coupon;
      delete updatePayload.food_coupon_name;
      const { data: fbUpdated, error: fbErr } = await supabase
        .from('event_attendance_periods')
        .update(updatePayload)
        .eq('id', periodId)
        .eq('event_id', eventId)
        .select()
        .single();
      if (fbErr) throw fbErr;
      updatedPeriod = { ...fbUpdated, includes_food_coupon: hasFood, food_coupon_name: couponName };
    } else if (error) {
      throw error;
    } else {
      updatedPeriod = uPeriod;
    }

    return res.json({ success: true, message: 'Attendance period updated.', period: updatedPeriod });
  } catch (err) {
    console.error('Error updating period:', err);
    return res.status(500).json({ message: 'Server error updating period.', error: err.message });
  }
};

